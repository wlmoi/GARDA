#!/usr/bin/env python3
"""Reproducible GARDA DE10-Lite build: Quartus synthesis, fit, timing, assembly.

  python scripts/build.py [--quartus D:/OldQuartus/quartus/bin64] [--baud 115200|921600]

Writes rtl/de10_lite/garda_build_config.vh (BUILD_ID = UNIX time, baud divisor),
runs `quartus_sh --flow compile`, parses the reports and writes
output/build_manifest.json plus a copy of the .sof. The .sof is only marked
"release": true when synthesis, fit and assembly succeed AND every timing corner
has non-negative setup, hold, recovery and removal slack.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
QDIR = ROOT / "quartus"
OUT = QDIR / "output_files"
sys.path.insert(0, str(ROOT / "host"))
from garda_quartus import find_quartus_bin  # noqa: E402

CLOCK_HZ = 45_000_000   # core clock from the MAX 10 PLL (rtl/de10_lite/garda_clock.v)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_reports() -> dict:
    fit = (OUT / "garda_de10_lite.fit.summary").read_text(errors="replace")
    sta = (OUT / "garda_de10_lite.sta.rpt").read_text(errors="replace")
    def grab(label):
        m = re.search(rf"{label}\s*:\s*(.+)", fit)
        return m.group(1).strip() if m else None
    corners = {}
    names = ["Slow 1200mV 85C", "Slow 1200mV 0C", "Fast 1200mV 0C"]
    for kind in ("setup", "hold", "recovery", "removal"):
        vals = [float(v) for v in re.findall(rf"Worst-case {kind} slack is (-?[\d.]+)", sta)]
        for name, v in zip(names, vals):
            corners.setdefault(name, {})[kind] = v
    fmax = {}
    for mhz, clk in re.findall(r";\s*([\d.]+) MHz\s*;\s*[\d.]+ MHz\s*;\s*(\S+)\s*;", sta):
        fmax[clk] = min(float(mhz), fmax.get(clk, 1e9))   # worst (lowest) over the corners
    worst = min((v for c in corners.values() for v in c.values()), default=None)
    return {
        "fitter_status": grab("Fitter Status"), "quartus_version": grab("Quartus Prime Version"),
        "device": grab("Device"), "family": grab("Family"),
        "logic_elements": grab("Total logic elements"), "registers": grab("Total registers"),
        "memory_bits": grab("Total memory bits"), "multipliers_9bit": grab("Embedded Multiplier 9-bit elements"),
        "pins": grab("Total pins"), "pll": grab("Total PLLs"),
        "timing_corners": corners, "worst_slack_ns": worst,
        "fmax_mhz_by_clock": fmax,
        "fmax_mhz_worst_corner": min((v for k, v in fmax.items() if "pll" in k), default=None),   # core clock
        "timing_met": worst is not None and worst >= 0 and len(corners) == 3,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quartus", help="Quartus bin64 directory (default: auto-detect a Lite/licensed install)")
    ap.add_argument("--baud", type=int, default=115200, choices=[115200, 921600])
    args = ap.parse_args()
    qbin = Path(args.quartus) if args.quartus else find_quartus_bin()
    if not qbin:
        print("Quartus not found. Install Quartus Prime Lite with MAX 10 support.", file=sys.stderr)
        return 2
    clks = round(CLOCK_HZ / args.baud)
    build_id = int(time.time()) & 0xFFFFFFFF
    (ROOT / "rtl/de10_lite/garda_build_config.vh").write_text(
        "// Generated by scripts/build.py; defaults used for simulation and manual Quartus runs.\n"
        f"`define GARDA_CLOCK_HZ 32'd{CLOCK_HZ}\n"
        f"`define GARDA_CLKS_PER_BIT 16'd{clks}\n`define GARDA_BUILD_ID 32'h{build_id:08X}\n")
    subprocess.run([sys.executable, str(ROOT / "scripts/gen_vga_screen.py")], check=True)
    print(f"BUILD_ID 0x{build_id:08X}  baud {args.baud} (divisor {clks}, actual {CLOCK_HZ / clks:.0f})")
    log = QDIR / "compile.log"
    shutil.rmtree(OUT, ignore_errors=True)   # never parse reports of a previous build
    t0 = time.time()
    with log.open("w") as fh:
        rc = subprocess.run([str(qbin / "quartus_sh.exe" if (qbin / "quartus_sh.exe").exists() else qbin / "quartus_sh"),
                             "--flow", "compile", "garda_de10_lite"], cwd=QDIR, stdout=fh, stderr=subprocess.STDOUT).returncode
    elapsed = time.time() - t0
    sof = OUT / "garda_de10_lite.sof"
    manifest = {"build_id": f"0x{build_id:08X}", "build_time_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(build_id)),
                "quartus_exit_code": rc, "compile_seconds": round(elapsed), "baud": args.baud, "clks_per_bit": clks,
                "clock_hz": CLOCK_HZ, "top": "garda_de10_lite_top", "target_board": "Terasic DE10-Lite",
                "expected_jtag_idcode": "0x031050DD"}
    if (OUT / "garda_de10_lite.fit.summary").exists() and (OUT / "garda_de10_lite.sta.rpt").exists():
        manifest.update(parse_reports())
    manifest["sof_present"] = rc == 0 and sof.exists()
    manifest["release"] = bool(manifest["sof_present"] and manifest.get("timing_met"))
    out_dir = ROOT / "output"
    out_dir.mkdir(exist_ok=True)
    if manifest["sof_present"]:
        name = "garda_de10_lite.sof" if manifest["release"] else "garda_de10_lite_TIMING_NOT_MET.sof"
        shutil.copy2(sof, out_dir / name)
        manifest["sof_file"] = name
        manifest["sof_sha256"] = sha256(out_dir / name)
        pof = OUT / "garda_de10_lite.pof"
        if pof.exists():
            shutil.copy2(pof, out_dir / "garda_de10_lite.pof")
            manifest["pof_file"] = "garda_de10_lite.pof"
    reports = ROOT / "reports/quartus"
    reports.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*.rpt"):
        shutil.copy2(f, reports / f.name)
    for f in OUT.glob("*.summary"):
        shutil.copy2(f, reports / f.name)
    (out_dir / "build_manifest.json").write_text(json.dumps(manifest, indent=2))
    print(json.dumps(manifest, indent=2))
    return 0 if manifest["release"] else 1


if __name__ == "__main__":
    sys.exit(main())
