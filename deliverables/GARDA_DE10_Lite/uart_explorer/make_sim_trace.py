"""Generate traces/sample_simulation_trace.json from the SIMULATION demo. Provenance is SIMULATION, not hardware."""
import json, time
import explorer as X
h = X.Hub(); h.connect("SIMULATION"); h.start_demo(); h.demo_thread.join(30)
evs = list(h.ring)
out = {"provenance": {"mode": "SIMULATION", "note": "Generated by make_sim_trace.py from the software protocol model. NOT captured from an FPGA.",
                      "generated": time.time(), "baud": 115200, "framing": "8N1"}, "events": evs}
open(X.ROOT / "traces/sample_simulation_trace.json", "w").write(json.dumps(out, indent=1))
print(len(evs), "events", h.demo["overall"])
