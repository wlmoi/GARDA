from PIL import Image, ImageOps, ImageDraw, ImageFont
im = Image.open('asic/sky130_garda/seno.png').convert('RGBA')
a = im.getchannel('A')
im = im.crop(a.getbbox())
im.thumbnail((780, 1300), Image.Resampling.LANCZOS)
out = Image.new('RGB', (900, 1500), '#071741')
out.paste(im, ((900-im.width)//2, 80), im)
draw = ImageDraw.Draw(out)
font = ImageFont.truetype('C:/Windows/Fonts/arialbd.ttf', 100)
draw.text((450, 1420), 'GARDA', font=font, fill='#9bfd08', anchor='mm')
out.save('asic/sky130_garda/seno-garda-concept.png')
